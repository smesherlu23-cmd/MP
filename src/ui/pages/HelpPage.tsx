// Справка по программе и механикам расчёта.

import { COEFFICIENTS } from '../../engine';
import { openTab, useApp } from '../store';

const k = (key: string) => COEFFICIENTS.find((c) => c.key === key)?.label ?? key;

export function HelpPage() {
  const rs = Object.values(useApp((s) => s.rulesets))[0];
  const link = (sub: string, text: string) =>
    rs ? (
      <a href="#" onClick={(e) => (e.preventDefault(), openTab('ruleset', rs.id, { sub }))}>
        {text}
      </a>
    ) : (
      text
    );
  return (
    <div className="page help">
      <h1>Справка</h1>
      <p className="muted">Все числа, упомянутые ниже, хранятся в наборе правил и меняются в программе — код менять не нужно.</p>

      <h2>Порядок работы</h2>
      <ol>
        <li>
          <b>Набор правил</b> — «физика» эпохи: классы целей, дистанции, {link('types', 'каталог типов')} (люди, расчётное вооружение, техника и их огневая мощь),
          приказы, уровни опыта и командиров, условия боя, укрепления, разведданные, свои правила, {link('coefficients', 'коэффициенты и пороги')}. Ненужные
          механики можно {link('features', 'выключить')}.
        </li>
        <li>
          <b>Подразделения</b> — дерево: формирование (батальон) → вложенные подразделения → элементы (роты, штаб, батареи). Элемент состоит из типов каталога
          (штат / в строю) и имеет состояние: опыт 1–N, мораль, слаженность, готовность, боезапас, топливо, снаряжение, усталость, состояние техники,
          атаку и защиту в процентах.
        </li>
        <li>
          <b>Сценарий</b> — две стороны, их подразделения (копии из библиотеки), укрепления, разведданные, задачи; местность, время суток, погода и другие
          условия; начальная дистанция, лимит ходов, сид.
        </li>
        <li>
          <b>Бой</b> — пошагово (с паузами для решений ГМ) или сразу до конца. <b>Массовое моделирование</b> — сотни прогонов для оценки вероятностей.
        </li>
      </ol>

      <h2>Как устроен ход</h2>
      <h3>1. Обнаружение</h3>
      <p>
        Для каждого элемента противника: шанс = база дистанции × обнаружение наблюдателя ÷ скрытность цели. Скрытность растёт от приказа (засада, разведка,
        оборона), эшелона, местности и укреплений, падает, если цель стреляла в прошлом ходу. Учитываются до трёх лучших наблюдателей; разведка (приказ
        «разведка» или тег разведки) наблюдает в полную силу, остальные — с весом «{k('observerWeight')}». По необнаруженной цели огонь ведётся с
        множителем «{k('unspottedFireMult')}».
      </p>
      <h3>2. Инициатива</h3>
      <p>
        Инициатива стороны = 50 × средний множитель инициативы её элементов (опыт, командиры, условия, разведданные) × связь + случайная часть. Сторона с
        инициативой стреляет первой: противник отвечает уже с потерями и подавлением. Необнаруженная засада всегда получает инициативу, а её первый залп
        усилен.
      </p>
      <h3>3. Огонь и выбор целей</h3>
      <p>
        Огонь элемента = Σ (численность × огневая мощь типа против класса цели на текущей дистанции) × состояние × модификаторы × случайность. Состояние —
        слаженность, готовность, мораль, снаряжение, усталость, подавление, боезапас, связь и «атака %». Модификаторы — приказ, опыт, командиры (вышестоящие
        — ослабленно), условия, укрепления, разведданные и свои правила.
      </p>
      <p>
        Огонь распределяется по целям пропорционально: эффективность против класса × √(боевая ценность цели) × подставленность (эшелон × приказ) × видимость ×
        преследование (по отходящим и бегущим огонь сильнее). Навесной огонь достаёт второй эшелон и тыл.
      </p>
      <h3>4. Потери</h3>
      <p>
        Воздействие делится на защищённость цели (приказ, опыт, местность, укрепления при обороне, закрепление, «защита %», правила) и умножается на
        летальность класса и «{k('casualtyScale')}». Вероятность поражения каждой единицы — p = 1 − e^(−H / (N × защищённость типа)), а число потерь
        разыгрывается биномиально. Поэтому группа из 2–3 бойцов получает целые, правдоподобные потери, а у тысяч разброс сглаживается.
      </p>
      <p>
        Потери людей делятся на убитых, раненых и пропавших (у бегущих пропавших/пленных больше). Поражённая техника либо уничтожена, либо повреждена
        (ремонтопригодна); экипаж несёт потери. При бегстве техника бросается.
      </p>
      <h3>5. Подавление, движение, снабжение, усталость</h3>
      <ul>
        <li>Подавление растёт от входящего огня (с учётом «подавляющего действия» оружия), снижает огонь, движение и мораль и спадает каждый ход.</li>
        <li>
          Дистанция сокращается, когда доля сил стороны в атаке (с учётом подвижности, подавления и топлива) превышает «{k('attackPressureMin')}».
          Техника на марше может сломаться.
        </li>
        <li>Боезапас расходуется при стрельбе и подвозится по уровню снабжения формирования (под огнём — медленнее). Топливо тратится на движение.</li>
        <li>Усталость растёт от приказа, местности, погоды и подавления; в резерве и при закреплении — снижается.</li>
      </ul>
      <h3>6. Мораль и слаженность</h3>
      <p>
        Мораль падает от потерь за ход, подавления, изнурения и нехватки боезапаса (умножается на «потери морали» — опыт, командир, условия; при низкой
        слаженности сильнее), восстанавливается вне огня и растёт, если противник несёт заметно большие потери. Слаженность снижается от потерь и плохой связи.
      </p>
      <h3>7. Проверки конца хода</h3>
      <ul>
        <li>
          <b>Уничтожение</b>: сохранилось меньше «{k('destroyedThreshold')}» начальной боевой ценности.
        </li>
        <li>
          <b>Паника</b>: мораль ниже «{k('panicMorale')}» — шанс бегства растёт к нулю морали; «стоять насмерть» вдвое снижает шанс.
        </li>
        <li>
          <b>Отступление</b>: низкая мораль, большие суммарные потери, шоковые потери за ход, нет боезапаса или формирование сломлено. Отходящий элемент
          выходит из боя через несколько ходов.
        </li>
        <li>
          <b>Штаб и распад</b>: потеря штаба снижает связь и лишает формирование командира; если выбыла большая часть сил формирования, оно «сломлено», и мораль
          остальных падает. Бегство соседей тоже бьёт по морали.
        </li>
        <li>
          <b>Резервы</b> вводятся автоматически, когда первая линия выбыла (или ГМ меняет их приказ).
        </li>
      </ul>
      <p>Бой заканчивается, когда у стороны не осталось сил на позициях, по лимиту ходов, если бой затих, или по решению ГМ.</p>

      <h2>Итоги</h2>
      <ul>
        <li>Потери: личный состав (убито / ранено / пропало), техника и вооружение по типам (уничтожено / повреждено / брошено).</li>
        <li>Остаточная боеспособность: сохранившаяся боевая ценность × мораль × слаженность × (1 − усталость) × боезапас — в процентах от начальной.</li>
        <li>Организация: слаженность × связь × сохранность штабов × состояние элементов (бежавшие и уничтоженные снижают её).</li>
        <li>Снабжение: средние боезапас, топливо и снаряжение.</li>
        <li>
          Задачи сторон дают оценку 0–100%; исход определяется разницей оценок и {link('outcomes', 'порогами уровней исхода')}. Если задач нет, они выводятся
          из приказов: атакующий — захватить позицию, обороняющийся — удержать.
        </li>
      </ul>

      <h2>Свои правила</h2>
      <p>
        В разделе {link('modifiers', '«Свои правила»')}: «если все условия выполнены — характеристика ×N». Условия: любое условие боя, дистанция, номер хода,
        свой приказ/поведение/тег/состав/опыт/эшелон/сторона, укрепления и разведданные стороны, класс цели и свойства противника. Примеры:
      </p>
      <ul>
        <li>Ночь И есть тег «ночное видение» → обнаружение ×1.8, огонь ×1.25.</li>
        <li>Застройка И ближняя дистанция И класс цели «Бронетехника» → огонь ×1.5.</li>
        <li>Тег «кавалерия» И местность «Лес» → огонь ×0.5, подвижность ×0.6.</li>
      </ul>
      <p>Каждое правило, повлиявшее на результат, видно в журнале: нажмите на запись, чтобы раскрыть разбор множителей.</p>

      <h2>Случайность и повторяемость</h2>
      <p>
        У каждого боя свой сид. Один и тот же сид при тех же данных и решениях ГМ даёт тот же бой: в меню боя «⋯» пункт «Переиграть с тем же сидом» повторяет бой, «Повторить с решениями ГМ»
        воспроизводит и ваши вмешательства. Прогон №k массового моделирования использует сид «база#k» — любой прогон можно открыть как обычный бой.
      </p>

      <h2>Балансировка</h2>
      <ul>
        <li>Начните с массового моделирования на 200–500 прогонов и посмотрите вероятности и разброс потерь.</li>
        <li>Слишком кровопролитно или слишком вяло — «{k('casualtyScale')}». Слишком быстро бегут — пороги паники и отхода, коэффициенты морали.</li>
        <li>Сравнивайте копии набора правил: «Дублировать» и меняйте один параметр за раз.</li>
        <li>Отсортируйте прогоны по потерям, откройте самый плохой и прочитайте журнал — так видно, что именно сломало баланс.</li>
      </ul>

      <h2>Клавиши</h2>
      <ul>
        <li>Ctrl+клик или средняя кнопка по ссылке — открыть во вкладке в фоне; средняя кнопка по вкладке — закрыть.</li>
        <li>Ctrl+W — закрыть вкладку, Ctrl+Tab / Ctrl+Shift+Tab — переключение, Ctrl+1…9 — вкладка по номеру, Ctrl+B — навигатор.</li>
        <li>В числовых полях: ↑/↓ — изменить на шаг, Shift — на 10 шагов.</li>
      </ul>

      <h2>Данные</h2>
      <p>
        Всё хранится в папке данных как JSON (путь — в настройках): <code>rulesets</code>, <code>formations</code>, <code>scenarios</code>, <code>battles</code>.
        Файлы можно копировать между компьютерами, передавать другим ГМ («Сохранить в файл…» в меню «⋯» объекта и «Импорт из файла…» в меню справа вверху) и править вручную. Движок можно запускать и без
        интерфейса: <code>npm run sim -- сценарий.json правила.json --runs 500</code>.
      </p>
    </div>
  );
}
