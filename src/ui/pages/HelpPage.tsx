/** **жирный** в тексте руководства. */
function rich(s: string): ReactNode {
  const parts = s.split(/\*\*(.+?)\*\*/g);
  return parts.length === 1 ? s : parts.map((p, i) => (i % 2 ? <b key={i}>{p}</b> : p));
}

function GuideBlocks({ blocks }: { blocks: GuideBlock[] }) {
  return (
    <>
      {blocks.map((b, i) => {
        if (typeof b === 'string') return <p key={i}>{rich(b)}</p>;
        if ('h' in b) return <h3 key={i}>{b.h}</h3>;
        if ('ul' in b)
          return (
            <ul key={i}>
              {b.ul.map((x, j) => (
                <li key={j}>{rich(x)}</li>
              ))}
            </ul>
          );
        if ('ol' in b)
          return (
            <ol key={i}>
              {b.ol.map((x, j) => (
                <li key={j}>{rich(x)}</li>
              ))}
            </ol>
          );
        return (
          <div key={i} className="help-table-wrap">
            <table className="help-table">
              <thead>
                <tr>
                  {b.head.map((h) => (
                    <th key={h}>{h}</th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {b.table.map((r, j) => (
                  <tr key={j}>
                    {r.map((c, n) => (
                      <td key={n} className={c.length <= 24 ? 'nw' : undefined}>
                        {rich(c)}
                      </td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        );
      })}
    </>
  );
}

