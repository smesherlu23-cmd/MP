/** Руководство в Markdown — для файла. */
export function guideMarkdown(): string {
  const out: string[] = ['# Руководство ГМ: принцип работы и баланс чисел', ''];
  for (const s of GM_GUIDE) {
    out.push(`## ${s.title}`, '');
    for (const b of s.blocks) {
      if (typeof b === 'string') out.push(b, '');
      else if ('h' in b) out.push(`### ${b.h}`, '');
      else if ('ul' in b) out.push(...b.ul.map((x) => `- ${x}`), '');
      else if ('ol' in b) out.push(...b.ol.map((x, i) => `${i + 1}. ${x}`), '');
      else
        out.push(`| ${b.head.join(' | ')} |`, `|${b.head.map(() => '---').join('|')}|`, ...b.table.map((r) => `| ${r.map((c) => c || ' ').join(' | ')} |`), '');
    }
  }
  return out.join('\n');
}
